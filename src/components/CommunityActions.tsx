"use client";

import React, { useState } from "react";
import { Check, Copy, Printer, Users } from "lucide-react";
import { Alert } from "@/components/ui/Alert";
import { Button } from "@/components/ui/Button";
import type { GrapAssessment } from "@/domain/types";

export interface CommunityActionsProps {
  readonly advisory: string;
  readonly grap: GrapAssessment;
  readonly locationName: string;
  readonly language?: "en" | "hi";
}

function GrapNotice({ grap }: { readonly grap: GrapAssessment }): React.JSX.Element {
  return (
    <Alert variant={grap.stage >= 3 ? "danger" : "warning"} title={grap.stageName}>
      <p className="mb-2">{grap.summary}</p>
      <ul className="mb-2 list-inside list-disc space-y-1">
        {grap.citizenActions.map((action, i) => (
          <li key={i}>{action}</li>
        ))}
      </ul>
      <p className="text-[11px] opacity-80">{grap.officialVerificationNote}</p>
    </Alert>
  );
}

interface CommunityHeaderProps {
  readonly language: "en" | "hi";
  readonly copied: boolean;
  readonly onCopy: () => Promise<void>;
}

function CommunityHeader({ language, copied, onCopy }: CommunityHeaderProps): React.JSX.Element {
  return (
    <div className="flex flex-wrap items-center justify-between gap-3 border-b border-slate-100 pb-3 dark:border-slate-800">
      <div className="flex items-center gap-3">
        <div className="rounded-xl bg-purple-100 p-2 text-purple-700 dark:bg-purple-950 dark:text-purple-300">
          <Users className="h-5 w-5" aria-hidden="true" />
        </div>
        <div>
          <h3 className="text-lg font-bold text-slate-900 dark:text-slate-100">
            {language === "hi" ? "सामुदायिक व RWA एडवाइजरी" : "Community & School Advisory"}
          </h3>
          <p className="text-xs text-slate-500">
            Shareable notice for apartment societies and schools
          </p>
        </div>
      </div>
      <div className="flex items-center gap-2">
        <Button type="button" variant="outline" size="sm" onClick={onCopy}>
          {copied ? (
            <Check className="mr-1 h-4 w-4 text-emerald-600" />
          ) : (
            <Copy className="mr-1 h-4 w-4" />
          )}
          <span>{copied ? "Copied!" : "Copy Notice"}</span>
        </Button>
        <Button type="button" variant="outline" size="sm" onClick={() => window.print()}>
          <Printer className="mr-1 h-4 w-4" />
          <span>Print</span>
        </Button>
      </div>
    </div>
  );
}

function CommunityBroadcast({ advisory }: { readonly advisory: string }): React.JSX.Element {
  return (
    <div className="rounded-xl border border-slate-200 bg-slate-50/50 p-4 text-sm leading-relaxed text-slate-800 dark:border-slate-800 dark:bg-slate-800/30 dark:text-slate-200">
      <h4 className="mb-2 font-semibold text-slate-900 dark:text-slate-100">
        Shareable Community Broadcast:
      </h4>
      <p className="whitespace-pre-line">{advisory}</p>
    </div>
  );
}

export function CommunityActions({
  advisory,
  grap,
  locationName,
  language = "en",
}: CommunityActionsProps): React.JSX.Element {
  const [copied, setCopied] = useState(false);

  const handleCopy = async (): Promise<void> => {
    const textToCopy = `[SmogShield Community Advisory - ${locationName}]\n\n${advisory}\n\n${
      grap.applicable ? `${grap.stageName}: ${grap.summary}\n` : ""
    }Generated by SmogShield.`;
    await navigator.clipboard.writeText(textToCopy);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  return (
    <section
      aria-label="Community and Neighborhood Actions"
      className="flex flex-col gap-5 rounded-2xl border border-slate-200 bg-white p-6 shadow-sm dark:border-slate-800 dark:bg-slate-900"
    >
      <CommunityHeader language={language} copied={copied} onCopy={handleCopy} />
      {grap.applicable && <GrapNotice grap={grap} />}
      <CommunityBroadcast advisory={advisory} />
    </section>
  );
}
